"""Generation of the Markdown index of all symbols in the library."""

from __future__ import annotations

import argparse
from pathlib import Path

from .config import LibraryConfig, get_config
from .validation import parse_symbol_file


def library_symbols(path: Path) -> list[tuple[str, str]]:
    """Return the name and Description of each top-level symbol in a symbol library."""
    symbols = []
    for symbol in parse_symbol_file(path):
        description = symbol.properties.get("Description")
        symbols.append((symbol.name, description.value.strip() if description else ""))
    return symbols


def render(config: LibraryConfig) -> str:
    """Return the Markdown index for every symbol library in ``config``."""
    libs: list[tuple[str, list[tuple[str, str]]]] = []
    for path in sorted(config.symbol_path.glob("*.kicad_sym")):
        symbols = library_symbols(path)
        if symbols:
            libs.append((path.stem, symbols))

    lines = [
        f"# {config.library_prefix} KiCad Libraries",
        "",
        "<!-- Auto-generated by `kicad-lib libraries-md`; do not edit -->",
        "",
        "| Library | Components |",
        "|---|---|",
    ]
    for lib_name, symbols in libs:
        anchor = lib_name.lower().replace("_", "-")
        lines.append(f"| [{lib_name}](#{anchor}) | {len(symbols)} |")
    lines.append("")

    for lib_name, symbols in libs:
        lines.append(f"## {lib_name}")
        lines.append("")
        for name, description in symbols:
            entry = f"- **{name}**"
            if description:
                entry += f" — {description}"
            lines.append(entry)
        lines.append("")

    return "\n".join(lines) + "\n"


def main(argv: list[str] | None = None) -> int:
    """Run ``kicad-lib libraries-md`` and return its exit code."""
    argparse.ArgumentParser(
        prog="kicad-lib libraries-md",
        description="Regenerate the Markdown index of all symbols.",
    ).parse_args(argv)
    config = get_config()
    config.libraries_md_path.write_text(render(config), encoding="utf-8")
    print(f"Generated {config.libraries_md_path.relative_to(config.repo_root)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
